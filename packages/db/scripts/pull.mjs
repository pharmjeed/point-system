// Regenerates src/schema/schema.ts from a migrated database (DATABASE_URL) with drizzle-kit pull.
// Foreign keys are dropped from the Drizzle definitions (they live in the SQL migration) so that
// cyclic references between tables don't degrade the inferred types to `any`.
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, rmSync, mkdirSync } from 'node:fs';

execSync('npx drizzle-kit pull', { stdio: 'inherit' });
let src = readFileSync('drizzle/schema.ts', 'utf8');
let out = '';
for (let i = 0; i < src.length;) {
  const at = src.indexOf('foreignKey({', i);
  if (at < 0) {
    out += src.slice(i);
    break;
  }
  out += src.slice(i, at);
  let depth = 0,
    j = at + 'foreignKey('.length;
  for (; j < src.length; j++) {
    if (src[j] === '(') depth++;
    if (src[j] === ')') {
      if (depth === 0) break;
      depth--;
    }
  }
  j++; // past ')'
  while (src[j] === '.') {
    // .onDelete("cascade") chains
    const close = src.indexOf(')', j);
    j = close + 1;
  }
  if (src[j] === ',') j++;
  i = j;
}
out = out
  .replace(/\n\s*\n(\s*\])/g, '\n$1')
  .replace(/, type AnyPgColumn/, '')
  .replace(/foreignKey, /, '');
out = '// Generated by scripts/pull.mjs from the migrated database. Do not edit by hand.\n' + out;
mkdirSync('src/schema', { recursive: true });
writeFileSync('src/schema/schema.ts', out);
execSync('npx prettier --write src/schema/schema.ts', { stdio: 'inherit' });
rmSync('drizzle', { recursive: true, force: true });
console.log('src/schema/schema.ts regenerated');
